export function createShopWorkspace(files: Record<string, string> = SHOP_FILES): Workspace {
  return createMemoryWorkspace(files, { symbolsOfFile: scriptSymbolsOfFile })
}

// The position of a name inside a piece of code of a file: positionIn(path, 'await loadOrder(id)', 'loadOrder') is a
// click in the middle of loadOrder on that line.
export function positionIn(
  path: string,
  code: string,
  name: string = code,
  files: Record<string, string> = SHOP_FILES,
): CodePosition {
  const text = files[path] ?? ''
  const codeOffset = text.indexOf(code)
  const nameOffset = code.indexOf(name)
  if (codeOffset === -1 || nameOffset === -1) {
    throw new Error(`"${code}" with "${name}" is not in ${path}`)
  }
  const offset = codeOffset + nameOffset + Math.floor(name.length / 2)
  const textBefore = text.slice(0, offset)
  const line = textBefore.split('\n').length

  return { path, line, column: offset - (textBefore.lastIndexOf('\n') + 1) }
}

export function lineOf(path: string, code: string, files: Record<string, string> = SHOP_FILES): number {
  const offset = (files[path] ?? '').indexOf(code)
  if (offset === -1) {
    throw new Error(`"${code}" is not in ${path}`)
  }

  return (files[path] ?? '').slice(0, offset).split('\n').length
}
